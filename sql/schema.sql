-- Existing runs with a real snapshot can be backfilled from their immutable
-- foreign key. Runs with a missing or sentinel snapshot version remain blocked
-- for explicit remediation rather than being misrepresented as pre-snapshot.
UPDATE tariff.agent_runs
SET requested_notice_id = notice_id,
    snapshot_obtained = TRUE
WHERE requested_notice_id IS NULL
  AND notice_id IS NOT NULL
  AND policy_snapshot_version ~ '^[0-9a-fA-F]{64}$';

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM tariff.agent_runs
        WHERE requested_notice_id IS NULL
           OR snapshot_obtained IS NULL
           OR (
                snapshot_obtained
                AND (
                    notice_id IS NULL
                    OR policy_snapshot_version IS NULL
                    OR policy_snapshot_version !~ '^[0-9a-fA-F]{64}$'
                )
           )
           OR (
                NOT snapshot_obtained
                AND (notice_id IS NOT NULL OR policy_snapshot_version IS NOT NULL)
           )
           OR NULLIF(BTRIM(COALESCE(scenario_version, '')), '') IS NULL
           OR LOWER(BTRIM(COALESCE(scenario_version, ''))) = 'unavailable'
           OR NULLIF(BTRIM(COALESCE(enterprise_data_version, '')), '') IS NULL
           OR LOWER(BTRIM(COALESCE(enterprise_data_version, ''))) = 'unavailable'
           OR NULLIF(BTRIM(COALESCE(classification_schedule_version, '')), '') IS NULL
           OR LOWER(BTRIM(COALESCE(classification_schedule_version, ''))) = 'unavailable'
           OR NULLIF(BTRIM(COALESCE(analysis_version, '')), '') IS NULL
           OR LOWER(BTRIM(COALESCE(analysis_version, ''))) = 'unavailable'
           OR NULLIF(BTRIM(COALESCE(model_version, '')), '') IS NULL
           OR LOWER(BTRIM(COALESCE(model_version, ''))) = 'unavailable'
           OR NULLIF(BTRIM(COALESCE(prompt_version, '')), '') IS NULL
           OR LOWER(BTRIM(COALESCE(prompt_version, ''))) = 'unavailable'
    ) THEN
        RAISE EXCEPTION USING
            MESSAGE = 'Agent Run migration requires canonical attempt state and version records.',
            HINT = 'Backfill every retained snapshot-obtained Agent Run with genuine input, model, and prompt versions; explicitly model pre-snapshot attempts before rerunning initialization.';
    END IF;
END
