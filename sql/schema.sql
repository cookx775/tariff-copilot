-- Do not silently convert pre-canonical records into valid Outlooks.  The
-- migration stops until every retained legacy row has real deterministic
-- versions and policy-window evidence, after which these columns are made
-- canonical for all writes.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM tariff.impact_outlook_snapshots
        WHERE NULLIF(BTRIM(COALESCE(policy_snapshot_version, '')), '') IS NULL
           OR LOWER(BTRIM(COALESCE(policy_snapshot_version, ''))) = 'unavailable'
           OR NULLIF(BTRIM(COALESCE(scenario_version, '')), '') IS NULL
           OR LOWER(BTRIM(COALESCE(scenario_version, ''))) = 'unavailable'
           OR NULLIF(BTRIM(COALESCE(enterprise_data_version, '')), '') IS NULL
           OR LOWER(BTRIM(COALESCE(enterprise_data_version, ''))) = 'unavailable'
           OR NULLIF(BTRIM(COALESCE(classification_schedule_version, '')), '') IS NULL
           OR LOWER(BTRIM(COALESCE(classification_schedule_version, ''))) = 'unavailable'
           OR NULLIF(BTRIM(COALESCE(analysis_version, '')), '') IS NULL
           OR LOWER(BTRIM(COALESCE(analysis_version, ''))) = 'unavailable'
           OR NULLIF(BTRIM(COALESCE(impact_window_label, '')), '') IS NULL
           OR LOWER(BTRIM(COALESCE(impact_window_label, ''))) = 'unavailable'
           OR (
                impact_window_start IS NOT NULL
                AND (
                    impact_window_policy_chunk_id IS NULL
                    OR NULLIF(BTRIM(COALESCE(impact_window_policy_citation, '')), '') IS NULL
                    OR LOWER(BTRIM(COALESCE(impact_window_policy_citation, ''))) = 'unavailable'
                    OR NULLIF(BTRIM(COALESCE(impact_window_policy_chunk_text, '')), '') IS NULL
                    OR LOWER(BTRIM(COALESCE(impact_window_policy_chunk_text, ''))) = 'unavailable'
                )
            )
    ) THEN
        RAISE EXCEPTION USING
            MESSAGE = 'Impact Outlook migration requires backfilled canonical snapshot versions and policy-window evidence.',
            HINT = 'Backfill the retained legacy rows with genuine source facts, or preserve them outside the canonical Outlook tables before rerunning initialization.';
    END IF;
END
$$;

